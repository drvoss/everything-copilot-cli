#!/usr/bin/env node
/**
 * build-plugin-bundles — materializes Copilot CLI plugin bundles from `skills/`.
 *
 *   node scripts/build-plugin-bundles.mjs            # (re)generate plugins/<name>/
 *   node scripts/build-plugin-bundles.mjs --check    # fail if the committed output is stale
 *
 * Why generate instead of hand-maintaining a second copy:
 *   the Copilot plugin loader wants skill folders FLAT under the plugin's skills
 *   path, but this repo organises them as skills/<category>/<skill>/. Copying by
 *   hand creates two sources of truth; generating keeps `skills/` authoritative.
 *   The generated tree is still committed because awesome-copilot reviews an
 *   immutable commit SHA — the files must exist at that SHA.
 *
 * Single source of truth for what goes in a bundle: plugins/bundles.json
 */
import { readFileSync, writeFileSync, mkdirSync, rmSync, cpSync, existsSync, readdirSync } from "node:fs";
import { resolve, join, relative } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const DEFS = resolve(ROOT, "plugins/bundles.json");
const check = process.argv.includes("--check");

const pkg = JSON.parse(readFileSync(resolve(ROOT, "package.json"), "utf8"));
const defs = JSON.parse(readFileSync(DEFS, "utf8"));

const meta = {
  author: defs.author,
  homepage: defs.homepage ?? pkg.repository?.url,
  repository: pkg.repository?.url,
  license: pkg.license,
};

function listFiles(dir, base = dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...listFiles(p, base));
    else out.push(relative(base, p).replace(/\\/g, "/"));
  }
  return out.sort();
}

function snapshot(dir) {
  if (!existsSync(dir)) return null;
  const files = listFiles(dir);
  return files.map((f) => `${f}\n${readFileSync(join(dir, f), "utf8")}`).join("\n \n");
}

const drift = [];

for (const b of defs.bundles) {
  const outDir = resolve(ROOT, "plugins", b.name);
  const before = check ? snapshot(outDir) : null;

  const tmp = check ? resolve(ROOT, "plugins", `.${b.name}.check`) : outDir;
  rmSync(tmp, { recursive: true, force: true });
  mkdirSync(join(tmp, "skills"), { recursive: true });

  const seen = new Set();
  for (const rel of b.skills) {
    const src = resolve(ROOT, "skills", rel);
    if (!existsSync(join(src, "SKILL.md"))) {
      console.error(`build-plugin-bundles: missing skill — skills/${rel}/SKILL.md`);
      process.exit(1);
    }
    const name = rel.split("/").pop();
    if (seen.has(name)) {
      console.error(`build-plugin-bundles: duplicate skill name "${name}" in bundle "${b.name}"`);
      process.exit(1);
    }
    seen.add(name);
    cpSync(src, join(tmp, "skills", name), { recursive: true });
  }

  const manifest = {
    name: b.name,
    description: b.description,
    version: b.version,
    author: meta.author,
    homepage: meta.homepage,
    repository: meta.repository,
    license: meta.license,
    keywords: b.keywords,
    skills: "./skills/",
  };
  writeFileSync(join(tmp, "plugin.json"), JSON.stringify(manifest, null, 2) + "\n", "utf8");
  writeFileSync(
    join(tmp, "README.md"),
    `# ${b.name}\n\n${b.description}\n\n> Generated by \`scripts/build-plugin-bundles.mjs\` from \`plugins/bundles.json\`.\n> Edit the skills under \`skills/\` in the repository root — not the copies here.\n\n## Install\n\n\`\`\`bash\ncopilot plugin install ${b.name}@awesome-copilot\n# or, straight from this repository:\ncopilot plugin install drvoss/everything-copilot-cli:plugins/${b.name}\n\`\`\`\n\n## Skills (${b.skills.length})\n\n${b.skills.map((s) => `- \`${s.split("/").pop()}\``).join("\n")}\n`,
    "utf8"
  );

  if (check) {
    const after = snapshot(tmp);
    rmSync(tmp, { recursive: true, force: true });
    if (before !== after) drift.push(b.name);
  } else {
    console.log(`build-plugin-bundles: wrote plugins/${b.name}/ (${b.skills.length} skills, v${b.version})`);
  }
}

if (check) {
  if (drift.length) {
    console.error(`build-plugin-bundles: committed output is stale for: ${drift.join(", ")}`);
    console.error(`Run \`node scripts/build-plugin-bundles.mjs\` and commit the result.`);
    process.exit(1);
  }
  console.log("build-plugin-bundles: --check OK, no drift.");
}
